def normalize_query(text: str) -> str:
    return " ".join((text or "").strip().lower().split())


def resolve_commodities(crop: str) -> list[str]:
    """Expand a farmer crop query into related KAMIS commodity names.

    Always returns all matching variants (e.g. maize → dry/green/bran/flour).
    Falls back to substring match against the full catalog when no alias hits.
    """
    key = normalize_query(crop)
    if not key:
        return []

    if key in CROP_ALIASES:
        return list(CROP_ALIASES[key])

    # Singular/plural light fallback
    for alias_key, names in CROP_ALIASES.items():
        if key.startswith(alias_key) or alias_key.startswith(key):
            return list(names)

    matches = [
        name
        for name in PRODUCT_CATALOG.values()
        if key in name.lower() or name.lower() in key
    ]
    # De-dupe while preserving order
    seen: set[str] = set()
    out: list[str] = []
    for name in matches:
        if name not in seen:
            seen.add(name)
            out.append(name)
    return out
